function Expand-ProjectToolsWinRTTemplate([string]$Name, [hashtable]$Values) {
    $template = [IO.File]::ReadAllText((Join-Path $PSScriptRoot "../Templates/$Name"))
    [regex]::Replace($template, '@([A-Z]+)@', { param($match) $Values[$match.Groups[1].Value] })
}

function Get-ProjectToolsWinRTProjectionPath($Model, $Component) {
    if ($Model.Manifest.fileScope) {
        return Get-ProjectToolsOutputPath $Model $Component 'project-winrtProjection' ''
    }
    $native = Get-ProjectToolsLocation $Model $Component 'Dynamic'
    (Split-Path -Parent $native).Replace('\', '/') + '/' + $Component.projection.assemblyName + '.csproj'
}

function Get-ProjectToolsWinRTArtifactRoot($Model, [string]$Path, [string]$Name) {
    '$([System.IO.Path]::GetFullPath(''' + (Get-ProjectToolsRelativeImport $Model $Path ('!artifacts/projects/Windows/msbuild/' + $Name)) + '''))\'
}

function Get-ProjectToolsWinRTGraph($Model, [string[]]$Names) {
    $registry = @{}
    foreach ($component in $Model.Components.Values) {
        $registry[$component.name] = [pscustomobject]@{
            Kind = $component.kind; StateScope = $component.stateScope
            Variants = @(Get-ProjectToolsNativeVariants $component)
            Dependencies = @($component.dependencies | Where-Object { $_ } | ForEach-Object {
                [pscustomobject]@{ Component = $_.component; Visibility = $_.visibility; Linkage = $_.linkage }
            })
        }
    }
    $modes = @{}
    foreach ($name in $Names) { $modes[$name] = 'Dynamic' }
    Resolve-UdkLinkageGraph $Names $modes $registry
}

function Add-ProjectToolsWinRTPlan($Model, $Plan, $Projects) {
    $components = @($Model.Components.Values | Where-Object projectType -eq 'winrt')
    $apps = @($Model.Applications.Values | Where-Object projectType -eq 'winui')
    if (-not $components.Count -and -not $apps.Count) { return }
    if (@($Model.Settings.platforms | Where-Object { $_ -cnotin @('x64', 'ARM64', 'Win32') }).Count) {
        throw 'WinUI/WinRT supports x64, ARM64 and Win32 platforms only.'
    }
    $support = 'Projects/!Generated/MsBuild/WinRT.Support'
    $taskProject = "$support/ManifestTasks.csproj"
    $runtimeTargets = "$support/UniversalDevKit.WinRT.Runtime.g.targets"
    $taskOutput = '!artifacts/projects/Windows/msbuild/WinRT.ManifestTasks/bin/$(Configuration)/netstandard2.0/'
    function AddWinRTOutput([string]$Path, [string]$Content) {
        $absolute = Resolve-ProjectToolsPath $Model.Root $Path
        if (@($Plan | Where-Object Path -eq $absolute).Count) { throw "Duplicate WinRT output: $Path" }
        $original = if (Test-Path -LiteralPath $absolute) { [IO.File]::ReadAllText($absolute) } else { $null }
        $Plan.Add([pscustomobject]@{ Path = $absolute; RelativePath = $Path; Original = $original; Content = $Content.TrimEnd([char[]]"`r`n") })
    }
    $taskTemplate = [IO.File]::ReadAllText((Join-Path $PSScriptRoot '../WinRT/ManifestTasks.csproj'))
    $taskArtifacts = Get-ProjectToolsWinRTArtifactRoot $Model $taskProject 'WinRT.ManifestTasks'
    $taskTemplate = $taskTemplate.Replace('$(MSBuildThisFileDirectory)..\..\..\..\..\..\!artifacts\projects\Windows\msbuild\WinRT.ManifestTasks\', $taskArtifacts)
    $taskTemplate = $taskTemplate.Replace('<ItemGroup>', '<ItemGroup><PackageReference Include="Microsoft.Windows.CppWinRT" Version="2.0.250303.1" ExcludeAssets="all" PrivateAssets="all" />')
    $taskTemplate = $taskTemplate.Replace('<Project>', '<?xml version="1.0" encoding="utf-8"?>' + "`n<!-- Generated by ProjectTools. Edit WinRT/ManifestTasks.csproj. -->`n<Project>")
    AddWinRTOutput $taskProject $taskTemplate
    AddWinRTOutput "$support/ManifestTasks.g.cs" ('// Generated by ProjectTools. Edit WinRT/ManifestTasks.cs.' + "`n" + [IO.File]::ReadAllText((Join-Path $PSScriptRoot '../WinRT/ManifestTasks.cs')))
    AddWinRTOutput $runtimeTargets (Expand-ProjectToolsWinRTTemplate 'WinRT.Runtime.g.targets.in' @{})
    $byName = @{}
    foreach ($component in $Model.Components.Values) { $byName[$component.name] = $component }
    foreach ($component in $components) {
        $native = Get-ProjectToolsLocation $Model $component 'Dynamic'
        $projection = Get-ProjectToolsWinRTProjectionPath $Model $component
        $directory = (Split-Path -Parent $native).Replace('\', '/')
        $fragmentRoot = '!artifacts/projects/Windows/msbuild/' + $component.name
        $packageTargets = "$directory/$($component.name).NuGet.g.targets"
        $guid = Get-ProjectToolsGuid ($component.projectGuid + ':Projection')
        $Projects.Add([pscustomobject]@{
            Path = $projection; Guid = $guid; Variant = 'DotNet'; Component = $component.name
            SolutionFolder = Get-ProjectToolsLayout $Model $component 'Dynamic' 'solutionFolder'
            NativePlatform = $true
        })
        $nativeOutput = @($Plan | Where-Object RelativePath -eq $native)
        if ($nativeOutput.Count -ne 1) { throw "Expected one generated WinRT project: $native" }
        if (-not @($component.sources | Where-Object { [IO.Path]::GetExtension($_) -eq '.idl' }).Count) {
            throw "WinRT requires at least one IDL source: $($component.name)"
        }
        $packageRoot = @'
  <PropertyGroup>
    <UniversalDevKitCppWinRTVersion Condition="'$(UniversalDevKitCppWinRTVersion)' == ''">2.0.250303.1</UniversalDevKitCppWinRTVersion>
    <NuGetPackageRoot Condition="'$(NuGetPackageRoot)' == '' and '$(RestorePackagesPath)' != ''">$(RestorePackagesPath)\</NuGetPackageRoot>
    <NuGetPackageRoot Condition="'$(NuGetPackageRoot)' == '' and '$(NUGET_PACKAGES)' != ''">$(NUGET_PACKAGES)\</NuGetPackageRoot>
    <NuGetPackageRoot Condition="'$(NuGetPackageRoot)' == ''">$(UserProfile)\.nuget\packages\</NuGetPackageRoot>
    <__UniversalDevKitCppWinRT>$(NuGetPackageRoot)microsoft.windows.cppwinrt\$(UniversalDevKitCppWinRTVersion)\build\native\Microsoft.Windows.CppWinRT</__UniversalDevKitCppWinRT>
    <CppWinRTOptimized>true</CppWinRTOptimized>
    <CppWinRTGenerateWindowsMetadata>true</CppWinRTGenerateWindowsMetadata>
    <CppWinRTRootNamespaceAutoMerge>true</CppWinRTRootNamespaceAutoMerge>
  </PropertyGroup>
  <Import Project="$(__UniversalDevKitCppWinRT).props" Condition="Exists('$(__UniversalDevKitCppWinRT).props')" />
'@
        $nativeOutput[0].Content = $nativeOutput[0].Content.Replace('  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.props" />', $packageRoot + "`n" + '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.props" />')
        $nativeOutput[0].Content = $nativeOutput[0].Content.Replace('<RootNamespace>universaldevkit</RootNamespace>', '<RootNamespace>' + $component.name + '</RootNamespace>')
        $nativeOutput[0].Content = $nativeOutput[0].Content.Replace('<WindowsTargetPlatformVersion>10.0</WindowsTargetPlatformVersion>', '<WindowsTargetPlatformVersion>10.0.26100.0</WindowsTargetPlatformVersion>')
        $module = "$directory/WinRTModule.g.cpp"
        $exports = "$directory/Exports.g.def"
        AddWinRTOutput $module ('// Generated by ProjectTools. Edit the WinRT IDL and component implementation.' + "`n" + '#include "module.g.cpp"')
        AddWinRTOutput $exports ("; Generated by ProjectTools. Edit the WinRT generator.`nEXPORTS`n    DllGetActivationFactory=WINRT_GetActivationFactory PRIVATE`n    DllCanUnloadNow=WINRT_CanUnloadNow PRIVATE")
        $graph = Get-ProjectToolsWinRTGraph $Model @($component.name)
        $runtimeProjects = @($graph.ResolvedComponents | Where-Object { $_ -ne $component.name -and $byName[$_].projectType -ne 'winrt' -and $graph.ResolvedModes[$_] -eq 'Dynamic' } | ForEach-Object {
            $dependencyPath = Get-ProjectToolsLocation $Model $byName[$_] 'Dynamic'
            '    <__UniversalDevKitRuntimeProject Include="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $native $dependencyPath)) + '" />'
        }) -join "`n"
        $includeDirectories = @($graph.RequirementComponents | ForEach-Object {
            foreach ($includeDirectory in $byName[$_].compile.includeDirectories) {
                Get-ProjectToolsRelativeImport $Model $native $includeDirectory
            }
        } | Sort-Object -Unique) -join ';'
        $nativeExtras = @'
  <PropertyGroup>
    <TargetName>@NAME@</TargetName>
  </PropertyGroup>
  <ItemDefinitionGroup>
    <ClCompile><PrecompiledHeader>NotUsing</PrecompiledHeader><AdditionalOptions>/utf-8 %(AdditionalOptions)</AdditionalOptions><AdditionalIncludeDirectories>@INCLUDES@;%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories></ClCompile>
    <Link><ModuleDefinitionFile>@EXPORTS@</ModuleDefinitionFile><AdditionalDependencies>windowsapp.lib;%(AdditionalDependencies)</AdditionalDependencies></Link>
  </ItemDefinitionGroup>
  <ItemGroup>
    <ClCompile Include="@MODULE@" />
@RUNTIMEPROJECTS@
  </ItemGroup>
  <Import Project="$(__UniversalDevKitCppWinRT).targets" Condition="Exists('$(__UniversalDevKitCppWinRT).targets')" />
  <Target Name="Restore">
    <MSBuild Projects="@TASKPROJECT@" Targets="Restore" Properties="Configuration=$(Configuration)" RemoveProperties="Platform;RuntimeIdentifier;SelfContained" />
  </Target>
  <Target Name="__UniversalDevKitVerifyCppWinRT" BeforeTargets="PrepareForBuild">
    <Error Condition="!Exists('$(__UniversalDevKitCppWinRT).targets')" Text="Restore the solution before building the WinRT component (MSBuild /restore)." />
  </Target>
  <Target Name="__UniversalDevKitGetWinRTArtifacts" Returns="@(__UniversalDevKitNativeArtifact)">
    <ItemGroup>
      <__UniversalDevKitNativeArtifact Include="$(TargetPath)" WinMDPath="$(CppWinRTProjectWinMD)" />
    </ItemGroup>
    <MSBuild Projects="@(__UniversalDevKitRuntimeProject)" Targets="GetTargetPath" Properties="Configuration=$(Configuration);Platform=$(Platform)" Condition="'@(__UniversalDevKitRuntimeProject)' != ''">
      <Output TaskParameter="TargetOutputs" ItemName="__UniversalDevKitNativeArtifact" />
    </MSBuild>
    <ItemGroup>
      <__UniversalDevKitNativeArtifact>
        <RuntimeIdentifier>win-$([System.String]::Copy('$(Platform)').ToLowerInvariant())</RuntimeIdentifier>
        <RuntimeIdentifier Condition="'$(Platform)' == 'Win32'">win-x86</RuntimeIdentifier>
      </__UniversalDevKitNativeArtifact>
    </ItemGroup>
  </Target>
'@
        $nativeExtras = $nativeExtras.Replace('@NAME@', $component.name).
            Replace('@EXPORTS@', (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $native $exports))).
            Replace('@MODULE@', (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $native $module))).
            Replace('@RUNTIMEPROJECTS@', $runtimeProjects).
            Replace('@INCLUDES@', (ConvertTo-ProjectToolsXml $includeDirectories)).
            Replace('@TASKPROJECT@', (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $native $taskProject)))
        $nativeOutput[0].Content = $nativeOutput[0].Content.Replace('</Project>', $nativeExtras + "`n</Project>")
        $taskDirectory = Get-ProjectToolsRelativeImport $Model $projection ($taskOutput.Replace('$(Configuration)/netstandard2.0/', 'Release/netstandard2.0'))
        $taskDirectory = $taskDirectory.Replace('Release\netstandard2.0', '$(Configuration)\netstandard2.0') + '\'
        $projectionDependencies = @($graph.ResolvedComponents | Where-Object { $_ -ne $component.name -and $byName[$_].projectType -eq 'winrt' } | ForEach-Object {
            $dependencyProjection = Get-ProjectToolsWinRTProjectionPath $Model $byName[$_]
            $dependencyNative = Get-ProjectToolsLocation $Model $byName[$_] 'Dynamic'
            '    <ProjectReference Include="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $projection $dependencyProjection)) + '" />'
            '    <__UniversalDevKitMetadataProject Include="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $projection $dependencyNative)) + '" />'
        }) -join "`n"
        $values = @{
            FRAMEWORK = $component.projection.targetFramework; ASSEMBLY = $component.projection.assemblyName
            COMPONENT = $component.name; ARTIFACTS = Get-ProjectToolsWinRTArtifactRoot $Model $projection $component.name
            NATIVE = Get-ProjectToolsRelativeImport $Model $projection $native
            TASKPROJECT = Get-ProjectToolsRelativeImport $Model $projection $taskProject
            TASKDLL = $taskDirectory + 'UniversalDevKit.WinRT.ManifestTasks.dll'
            TASKDIRECTORY = $taskDirectory
            FRAGMENT = (Get-ProjectToolsRelativeImport $Model $projection $fragmentRoot) + '\$(Platform)\$(Configuration)\activation.g.manifest'
            PACKAGETARGETS = Get-ProjectToolsRelativeImport $Model $projection $packageTargets
            RUNTIMETARGETS = Get-ProjectToolsRelativeImport $Model $projection $runtimeTargets
            PLATFORMS = $Model.Settings.platforms -join ';'
            DEFAULTPLATFORM = $Model.Settings.platforms[0]
            DEPENDENCIES = $projectionDependencies
        }
        AddWinRTOutput $projection (Expand-ProjectToolsWinRTTemplate 'Library.WinRT.Projection.csproj.in' $values)
        $packageContent = @'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by ProjectTools. Edit the WinRT component description. -->
<Project>
  <PropertyGroup>
    <UniversalDevKitWinRTManifestTasks>$(MSBuildThisFileDirectory)..\tools\UniversalDevKit.WinRT.ManifestTasks.dll</UniversalDevKitWinRTManifestTasks>
  </PropertyGroup>
  <ItemGroup>
    <UniversalDevKitWinRTManifest Include="$(MSBuildThisFileDirectory)@NAME@.activation.manifest" />
  </ItemGroup>
  <Import Project="$(MSBuildThisFileDirectory)UniversalDevKit.WinRT.Runtime.g.targets" Condition="'$(OutputType)' == 'WinExe' or '$(OutputType)' == 'Exe'" />
  <Target Name="__UniversalDevKitValidate@TASKNAME@Runtime" BeforeTargets="PrepareForBuild" Condition="'$(OutputType)' == 'WinExe' or '$(OutputType)' == 'Exe'">
    <Error Condition="'$(RuntimeIdentifier)' == '' or !Exists('$(MSBuildThisFileDirectory)..\runtimes\$(RuntimeIdentifier)\native\@NAME@.dll')" Text="Select a Windows RuntimeIdentifier provided by the @NAME@ NuGet package." />
  </Target>
</Project>
'@
        AddWinRTOutput $packageTargets ($packageContent.Replace('@NAME@', $component.name).Replace('@TASKNAME@', $component.name.Replace('.', '_')))
    }
    foreach ($app in $apps) {
        $path = Get-ProjectToolsDotNetLocation $Model $app
        $output = @($Plan | Where-Object RelativePath -eq $path)[0]
        $directory = (Split-Path -Parent $path).Replace('\', '/')
        if (-not $app.sources.Count) {
            $namespace = $app.name
            $appXaml = @'
<Application x:Class="@NAMESPACE@.App" xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <Application.Resources>
    <ResourceDictionary><ResourceDictionary.MergedDictionaries><XamlControlsResources xmlns="using:Microsoft.UI.Xaml.Controls" /></ResourceDictionary.MergedDictionaries></ResourceDictionary>
  </Application.Resources>
</Application>
'@
            $appCode = @'
#nullable enable
using Microsoft.UI.Xaml;

namespace @NAMESPACE@;

public partial class App : Application
{
    private Window? window;

    public App()
    {
        InitializeComponent();
    }

    protected override void OnLaunched(LaunchActivatedEventArgs args)
    {
        window = new MainWindow();
        window.Activate();
    }
}
'@
            $windowXaml = '<Window x:Class="@NAMESPACE@.MainWindow" xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"><Grid /></Window>'
            $windowCode = @'
using Microsoft.UI.Xaml;

namespace @NAMESPACE@;

public sealed partial class MainWindow : Window
{
    public MainWindow()
    {
        InitializeComponent();
    }
}
'@
            $app.sources = @("$directory/App.g.xaml", "$directory/App.g.cs", "$directory/MainWindow.g.xaml", "$directory/MainWindow.g.cs")
            foreach ($entry in @{
                'App.g.xaml' = $appXaml; 'App.g.cs' = $appCode
                'MainWindow.g.xaml' = $windowXaml; 'MainWindow.g.cs' = $windowCode
            }.GetEnumerator()) {
                $comment = if ($entry.Key.EndsWith('.cs')) { '// Generated by ProjectTools. Add application sources to the component description.' } else { '<!-- Generated by ProjectTools. Add application sources to the component description. -->' }
                AddWinRTOutput ("$directory/" + $entry.Key) ($comment + "`n" + $entry.Value.Replace('@NAMESPACE@', $namespace))
            }
            $output.Content = New-ProjectToolsDotNetProject $Model $app $path
        }
        if (-not $app.msbuild.properties.ApplicationManifest) {
            $baseManifest = "$directory/Application.g.manifest"
            AddWinRTOutput $baseManifest ('<?xml version="1.0" encoding="utf-8"?>' + "`n<!-- Generated by ProjectTools. Set ApplicationManifest to provide a custom base manifest. -->`n" +
                '<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0"><assemblyIdentity name="' + $app.name + '" version="1.0.0.0" type="win32" /><trustInfo xmlns="urn:schemas-microsoft-com:asm.v3"><security><requestedPrivileges><requestedExecutionLevel level="asInvoker" uiAccess="false" /></requestedPrivileges></security></trustInfo></assembly>')
            $output.Content = $output.Content.Replace('<UseWinUI>', '<ApplicationManifest>' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $baseManifest)) + '</ApplicationManifest>' + "`n    <UseWinUI>")
        }
        $names = @($app.dependencies | Where-Object { $_ } | ForEach-Object component)
        foreach ($name in $names) {
            if (-not $byName.ContainsKey($name) -or $byName[$name].projectType -ne 'winrt') { throw "WinUI dependencies must name WinRT components: $name" }
        }
        if (-not $names.Count) { continue }
        $graph = Get-ProjectToolsWinRTGraph $Model $names
        $items = @('  <ItemGroup>')
        foreach ($name in $graph.ResolvedComponents | Where-Object { $byName[$_].projectType -eq 'winrt' }) {
            $component = $byName[$name]
            $projection = Get-ProjectToolsWinRTProjectionPath $Model $component
            $native = Get-ProjectToolsLocation $Model $component 'Dynamic'
            $fragmentRoot = "!artifacts/projects/Windows/msbuild/$name"
            $items += '    <ProjectReference Include="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $projection)) + '" />'
            $items += '    <UniversalDevKitWinRTManifest Include="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $fragmentRoot)) + '\$(Platform)\$(Configuration)\activation.g.manifest" />'
            $items += '    <__UniversalDevKitWinRTProject Include="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $native)) + '" />'
        }
        $items += '  </ItemGroup>'
        $taskDll = Get-ProjectToolsRelativeImport $Model $path '!artifacts/projects/Windows/msbuild/WinRT.ManifestTasks/bin/Release/netstandard2.0/UniversalDevKit.WinRT.ManifestTasks.dll'
        $taskDll = $taskDll.Replace('\Release\', '\$(Configuration)\')
        $items += '  <PropertyGroup><UniversalDevKitWinRTManifestTasks>' + (ConvertTo-ProjectToolsXml $taskDll) + '</UniversalDevKitWinRTManifestTasks></PropertyGroup>'
        $items += '  <Import Project="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $runtimeTargets)) + '" />'
        $copy = @'
  <Target Name="__UniversalDevKitResolveNativeRuntime" BeforeTargets="GetCopyToOutputDirectoryItems;ComputeFilesToPublish" DependsOnTargets="ResolveProjectReferences">
    <MSBuild Projects="@(__UniversalDevKitWinRTProject)" Targets="__UniversalDevKitGetWinRTArtifacts" Properties="Configuration=$(Configuration);Platform=$(Platform)">
      <Output TaskParameter="TargetOutputs" ItemName="__UniversalDevKitNativeRuntime" />
    </MSBuild>
    <ItemGroup>
      <ContentWithTargetPath Include="@(__UniversalDevKitNativeRuntime)" TargetPath="%(Filename)%(Extension)" CopyToOutputDirectory="PreserveNewest" CopyToPublishDirectory="PreserveNewest" />
    </ItemGroup>
  </Target>
'@
        $output.Content = $output.Content.Replace('</Project>', ($items -join "`n") + "`n" + $copy + "`n</Project>")
    }
}