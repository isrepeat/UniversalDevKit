function ConvertTo-ProjectToolsXml([string]$Value) { return [Security.SecurityElement]::Escape($Value) }

function Get-ProjectToolsApplicationProperties($Component, [string[]]$Reserved) {
    foreach ($property in $Component.msbuild.properties.PSObject.Properties) {
        if ($property.Name -notmatch '^[A-Za-z_][A-Za-z0-9_]*$' -or $property.Name -in $Reserved) {
            throw "Invalid application MSBuild property: $($property.Name)"
        }
        '    <' + $property.Name + '>' + (ConvertTo-ProjectToolsXml $property.Value) + '</' + $property.Name + '>'
    }
}

function Get-ProjectToolsFilter([string]$Path, $Component, [string]$Default) {
    if ($Component.filters.files -and $Component.filters.files.PSObject.Properties[$Path]) { return $Component.filters.files.PSObject.Properties[$Path].Value.Replace('/', '\') }
    $best = $null
    foreach ($rule in $Component.filters.roots) {
        if ($Path.StartsWith($rule.path + '/', [StringComparison]::Ordinal) -and ($null -eq $best -or $rule.path.Length -gt $best.path.Length)) { $best = $rule }
    }
    if ($null -ne $best) {
        $mapped = $Path.Substring($best.path.Length + 1)
        if ($best.filter) { $mapped = $best.filter + '/' + $mapped }
        return Split-Path -Parent $mapped.Replace('/', '\')
    }
    return $Default
}

function Get-ProjectToolsLocation($Model, $Component, [string]$Variant) {
    $directory = $Model.Settings.projectDirectory.Replace('{name}', $Component.name)
    $name = $Model.Settings.projectName.Replace('{name}', $Component.name).Replace('{variant}', $Variant)
    $extension = if ($Variant -eq 'Shared') { '.vcxitems' } else { '.vcxproj' }
    $path = $directory + '/' + $name + $extension
    $null = Resolve-ProjectToolsPath $Model.Root $path
    return $path
}

function Get-ProjectToolsRelativeImport($Model, [string]$ProjectPath, [string]$Target) {
    $directory = Split-Path -Parent (Join-Path $Model.Root $ProjectPath)
    $targetPath = Resolve-ProjectToolsPath $Model.Root $Target
    return '$(MSBuildThisFileDirectory)' + (Get-ProjectToolsRelativePath $directory $targetPath)
}

function Get-ProjectToolsBuildItems($Model, $Component, [string]$SharedPath, [string]$DependenciesPath) {
    $paths = @($Component.buildExtensions.msbuildProps, $Component.buildExtensions.msbuildTargets, $DependenciesPath) |
        Where-Object { $_ } | Select-Object -Unique
    if (-not $paths) { return }

    '  <ItemGroup>'
    foreach ($file in $paths) {
        $include = ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $SharedPath $file)
        '    <None Include="' + $include + '">'
        '      <__UniversalDevKitFilter>Build</__UniversalDevKitFilter>'
        '    </None>'
    }
    '  </ItemGroup>'
}

function New-ProjectToolsApplicationSharedProject($Model, $Component, [string]$Path, [string]$Guid) {
    $lines = @(
        '<?xml version="1.0" encoding="utf-8"?>'
        '<!-- Generated by ProjectTools. Edit the component description. -->'
        '<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">'
        '  <PropertyGroup Label="Globals">'
        '    <HasSharedItems>true</HasSharedItems>'
        "    <ItemsProjectGuid>$Guid</ItemsProjectGuid>"
        '  </PropertyGroup>'
        '  <ItemGroup>'
    )
    foreach ($group in @(@{ Type = 'ClInclude'; Files = $Component.headers }, @{ Type = 'ClCompile'; Files = $Component.sources })) {
        foreach ($file in $group.Files | Sort-Object -CaseSensitive) {
            $include = ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $Path $file)
            $filter = ConvertTo-ProjectToolsXml (Get-ProjectToolsFilter $file $Component (Split-Path -Parent $file.Replace('/', '\')))
            $lines += '    <' + $group.Type + ' Include="' + $include + '">'
            $lines += '      <__UniversalDevKitFilter>' + $filter + '</__UniversalDevKitFilter>'
            $lines += '    </' + $group.Type + '>'
        }
    }
    $lines += '  </ItemGroup>'
    $lines += @(Get-ProjectToolsBuildItems $Model $Component $Path)
    $lines += '</Project>'
    return $lines -join "`n"
}

function New-ProjectToolsApplicationProject($Model, $Component, [string]$Path, [string]$SharedPath) {
    $configurations = foreach ($configuration in $Model.Settings.configurations) {
        foreach ($platform in $Model.Settings.platforms) {
            '    <ProjectConfiguration Include="' + $configuration + '|' + $platform + '">'
            '      <Configuration>' + $configuration + '</Configuration>'
            '      <Platform>' + $platform + '</Platform>'
            '    </ProjectConfiguration>'
        }
    }
    $properties = Get-ProjectToolsApplicationProperties $Component @('ProjectGuid', 'Keyword', 'WindowsTargetPlatformVersion', 'UniversalDevKitGitHubVersion')
    if ($Component.githubVersion) {
        $properties = @('    <UniversalDevKitGitHubVersion>' + (ConvertTo-ProjectToolsXml $Component.githubVersion) + '</UniversalDevKitGitHubVersion>') + @($properties)
    }
    $props = foreach ($file in @($Component.buildExtensions.msbuildProps, 'Projects/MsBuild/BuildLayout.props') + @($Model.Settings.props)) {
        if ($file) { '  <Import Project="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $Path $file)) + '" />' }
    }
    $targets = foreach ($file in @($Component.buildExtensions.msbuildTargets) + @($Model.Settings.targets)) {
        if ($file) { '  <Import Project="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $Path $file)) + '" />' }
    }
    $standard = if ($Component.requirements.cxxStandard -eq 23) { 'stdcpplatest' } else { 'stdcpp20' }
    $template = [IO.File]::ReadAllText((Join-Path $PSScriptRoot '../Templates/Application.vcxproj.in'))
    $values = @{
        CONFIGURATIONS = $configurations -join "`n"
        GUID = ([Guid]$Component.msbuildGuid).ToString('B').ToUpperInvariant()
        PROPERTIES = $properties -join "`n"
        PROPS = $props -join "`n"
        STANDARD = $standard
        SHARED = ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $Path $SharedPath)
        TARGETS = $targets -join "`n"
    }
    return [regex]::Replace($template, '@([A-Z]+)@', { param($match) $values[$match.Groups[1].Value] })
}

function New-ProjectToolsWpfApplicationProject($Model, $Component, [string]$Path) {
    $properties = Get-ProjectToolsApplicationProperties $Component @('ProjectGuid', 'OutputType', 'UseWPF', 'Nullable')
    $directory = Split-Path -Parent (Resolve-ProjectToolsPath $Model.Root $Path)
    $roots = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    $filterFiles = [ordered]@{}
    foreach ($rule in $Component.filters.roots) {
        if ($rule.path -isnot [string] -or $rule.path -match '[*?]' -or
            @($rule.PSObject.Properties.Name).Count -ne 2 -or -not $rule.PSObject.Properties['filter']) {
            throw 'Expected path and filter in filters.roots.'
        }
        $root = Resolve-ProjectToolsPath $Model.Root $rule.path
        $relativeRoot = Get-ProjectToolsRelativePath $directory $root
        if ($relativeRoot -match '^\.\.(?:\\|$)' -or -not (Test-Path -LiteralPath $root -PathType Container) -or -not $roots.Add($root)) {
            throw "Expected a unique directory inside the project for filters.roots: $($rule.path)"
        }
        foreach ($file in Get-ChildItem -LiteralPath $root -File -Recurse | Sort-Object FullName) {
            $relative = Get-ProjectToolsRelativePath $directory $file.FullName
            if ($relative -match '(?:^|\\)(?:bin|obj|\.[^\\]+)\\' -or $file.Extension -in @('.csproj', '.user')) { continue }
            $repositoryPath = (Get-ProjectToolsRelativePath $Model.Root $file.FullName).Replace('\', '/')
            $filterFiles[$repositoryPath] = $file.FullName
        }
    }
    foreach ($entry in $Component.filters.files.PSObject.Properties) {
        $filterFiles[$entry.Name] = Resolve-ProjectToolsPath $Model.Root $entry.Name
    }
    $virtualFolders = @(
        foreach ($rule in $Component.filters.roots) { $rule.filter }
        foreach ($entry in $Component.filters.files.PSObject.Properties) { $entry.Value }
    )
    foreach ($filter in $virtualFolders) {
        if ($filter -isnot [string] -or $filter -match '[\\:*?"<>|$@%;\r\n]' -or
            ($filter -ne '' -and @($filter.Split('/') | Where-Object { $_ -in @('', '.', '..') }).Count)) {
            throw "Invalid virtual filter folder: $filter"
        }
    }
    $filterItems = foreach ($repositoryPath in $filterFiles.Keys) {
        $file = $filterFiles[$repositoryPath]
        $relative = Get-ProjectToolsRelativePath $directory $file
        if ($relative -match '^\.\.(?:\\|$)' -or $repositoryPath -match '[*?]' -or -not (Test-Path -LiteralPath $file -PathType Leaf)) {
            throw "Expected a file in the project directory for filters.files: $repositoryPath"
        }
        $link = [IO.Path]::GetFileName($file)
        $folder = Get-ProjectToolsFilter $repositoryPath $Component (Split-Path -Parent $relative)
        if ($folder) { $link = $folder + '\' + $link }
        $link = ConvertTo-ProjectToolsXml $link
        $include = ConvertTo-ProjectToolsXml $relative
        $itemTypes = switch ([IO.Path]::GetExtension($file)) {
            '.cs' { 'Compile' }
            '.xaml' {
                'Page'
                if ($relative -ieq 'App.xaml') { 'ApplicationDefinition' }
            }
            default { 'None' }
        }
        foreach ($type in $itemTypes) {
            '    <' + $type + ' Update="' + $include + '" Link="' + $link + '" />'
        }
    }
    $filters = if ($filterItems) { (@('  <ItemGroup>') + $filterItems + '  </ItemGroup>') -join "`n" }
    $imports = foreach ($file in @($Model.Settings.props) + @($Component.buildExtensions.msbuildProps, $Component.buildExtensions.msbuildTargets) + @($Model.Settings.targets)) {
        if ($file) { '  <Import Project="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $Path $file)) + '" />' }
    }
    $template = [IO.File]::ReadAllText((Join-Path $PSScriptRoot '../Templates/Application.Wpf.csproj.in'))
    $values = @{ PROPERTIES = $properties -join "`n"; FILTERS = $filters; IMPORTS = $imports -join "`n" }
    return [regex]::Replace($template, '@([A-Z]+)@', { param($match) $values[$match.Groups[1].Value] })
}

function New-ProjectToolsMsBuildPlan($Model, $UdkPlan) {
    $plan = [Collections.Generic.List[object]]::new()
    $projects = [Collections.Generic.List[object]]::new()
    foreach ($update in $UdkPlan) { $plan.Add($update) }
    $byName = @{}
    foreach ($component in $Model.Components.Values) { $byName[$component.name] = $component }
    $registry = @{}
    foreach ($component in $Model.Components.Values) {
        $registry[$component.name] = [pscustomobject]@{
            Kind = $component.kind; StateScope = $component.stateScope
            Dependencies = @($component.dependencies | Where-Object { $_ } | ForEach-Object { [pscustomobject]@{ Component = $_.component; Visibility = $_.visibility; Linkage = $_.linkage } })
        }
    }
    foreach ($component in $Model.Components.Values) {
        $mode = if ($component.stateScope -eq 'process') { 'Dynamic' } else { 'Shared' }
        $null = Resolve-UdkLinkageGraph @($component.name) @{ $component.name = $mode } $registry
    }
    function AddOutput([string]$Path, [string]$Content) {
        $absolute = Resolve-ProjectToolsPath $Model.Root $Path
        $content = $Content.TrimEnd([char[]]"`r`n")
        foreach ($existing in @($plan | Where-Object Path -eq $absolute)) { [void]$plan.Remove($existing) }
        $original = if (Test-Path -LiteralPath $absolute) { [IO.File]::ReadAllText($absolute) } else { $null }
        $plan.Add([pscustomobject]@{ Path = $absolute; RelativePath = $Path; Content = $content; Original = $original })
    }
    foreach ($component in $Model.Components.Values) {
        $variants = if ($component.kind -eq 'headerOnly') { @() } elseif ($component.variants) { @($component.variants | ForEach-Object { (Get-Culture).TextInfo.ToTitleCase($_) }) } elseif ($component.stateScope -eq 'process') { @('Dynamic') } else { @('Static', 'Dynamic') }
        if (@($variants | Where-Object { $_ -notin @('Static', 'Dynamic') }).Count -or @($variants | Select-Object -Unique).Count -ne $variants.Count) { throw 'Invalid or duplicate binary variant.' }
        if ($component.stateScope -eq 'process' -and 'Static' -in $variants) { throw 'Process state requires Dynamic.' }
        $sharedPath = Get-ProjectToolsLocation $Model $component 'Shared'
        $projects.Add([pscustomobject]@{ Path = $sharedPath; Guid = $component.msbuildGuid; Variant = 'Shared'; Component = $component.name })
        $sharedItems = [Collections.Generic.List[object]]::new()
        if ($component.msbuild.resolvedFiles) { AddOutput $component.msbuild.resolvedFiles (([ordered]@{ headers = @($component.headers); sources = @($component.sources) } | ConvertTo-Json -Depth 10 -Compress)) }
        if ($Model.Profile -ne 'udk') {
            $lines = [Collections.Generic.List[string]]::new()
            $lines.Add('<?xml version="1.0" encoding="utf-8"?>')
            $lines.Add('<!-- Generated by ProjectTools. Edit Components.json and its component descriptions. -->')
            $lines.Add('<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">')
            $lines.Add('  <PropertyGroup Label="Globals"><HasSharedItems>true</HasSharedItems><ItemsProjectGuid>' + $component.msbuildGuid + '</ItemsProjectGuid></PropertyGroup>')
            if ($component.buildExtensions.msbuildProps) { $lines.Add('  <Import Project="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $sharedPath $component.buildExtensions.msbuildProps)) + '" />') }
            $lines.Add('  <ItemDefinitionGroup><ClCompile>')
            $standard = if ($component.requirements.cxxStandard -eq 23) { 'stdcpplatest' } else { 'stdcpp20' }
            $lines.Add('    <LanguageStandard>' + $standard + '</LanguageStandard><ExceptionHandling>Sync</ExceptionHandling><AdditionalOptions>/utf-8 %(AdditionalOptions)</AdditionalOptions>')
            $includes = @($component.compile.includeDirectories | ForEach-Object { Get-ProjectToolsRelativeImport $Model $sharedPath $_ })
            if ($includes.Count) { $lines.Add('    <AdditionalIncludeDirectories>' + (ConvertTo-ProjectToolsXml ($includes -join ';')) + ';%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>') }
            if ($component.compile.preprocessorDefinitions) { $lines.Add('    <PreprocessorDefinitions>' + (ConvertTo-ProjectToolsXml ($component.compile.preprocessorDefinitions -join ';')) + ';%(PreprocessorDefinitions)</PreprocessorDefinitions>') }
            if ($component.compile.precompiledHeader -eq 'notUsing') { $lines.Add('    <PrecompiledHeader>NotUsing</PrecompiledHeader>') }
            $lines.Add('  </ClCompile></ItemDefinitionGroup>')
            $lines.Add('  <ItemGroup>')
            foreach ($group in @(@{ Type = 'ClInclude'; Files = $component.headers }, @{ Type = 'ClCompile'; Files = $component.sources })) {
                foreach ($file in $group.Files) {
                    $include = Get-ProjectToolsRelativeImport $Model $sharedPath $file
                    $filter = Split-Path -Parent (Get-ProjectToolsRelativePath (Split-Path -Parent (Join-Path $Model.Root $sharedPath)) (Join-Path $Model.Root $file))
                    $filter = Get-ProjectToolsFilter $file $component $filter
                    $sharedItems.Add(@{ Type = $group.Type; Include = $include; Filter = $filter })
                    $lines.Add('    <' + $group.Type + ' Include="' + (ConvertTo-ProjectToolsXml $include) + '" />')
                }
            }
            $lines.Add('  </ItemGroup>')
            $lines.Add('</Project>')
            AddOutput $sharedPath ($lines -join "`n")
            $filters = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
            foreach ($item in $sharedItems) { $filter = $item.Filter; while ($filter) { [void]$filters.Add($filter); $filter = Split-Path -Parent $filter } }
            $filterLines = @('<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by ProjectTools. Edit component file selections. -->', '<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">', '  <ItemGroup>')
            foreach ($filter in @($filters | Sort-Object)) { $filterLines += '    <Filter Include="' + (ConvertTo-ProjectToolsXml $filter) + '" />' }
            foreach ($item in $sharedItems) { $filterLines += '    <' + $item.Type + ' Include="' + (ConvertTo-ProjectToolsXml $item.Include) + '"><Filter>' + (ConvertTo-ProjectToolsXml $item.Filter) + '</Filter></' + $item.Type + '>' }
            $filterLines += @('  </ItemGroup>', '</Project>')
            AddOutput ($sharedPath + '.filters') ($filterLines -join "`n")
        }
        foreach ($variant in $variants) {
            $path = Get-ProjectToolsLocation $Model $component $variant
            $absolute = Join-Path $Model.Root $path
            $guid = Get-ProjectToolsGuid (([Guid]$component.msbuildGuid).ToString('D') + ':' + $variant)
            if (Test-Path -LiteralPath $absolute) {
                [xml]$old = [IO.File]::ReadAllText($absolute)
                $nodes = @($old.SelectNodes('/*[local-name()="Project"]/*[local-name()="PropertyGroup"]/*[local-name()="ProjectGuid"]'))
                if ($nodes.Count -ne 1) { throw "Invalid existing project GUID: $path" }
                $guid = '{' + ([Guid]$nodes[0].InnerText).ToString().ToUpperInvariant() + '}'
            }
            $projects.Add([pscustomobject]@{ Path = $path; Guid = $guid; Variant = $variant; Component = $component.name })
            if ($Model.Profile -eq 'udk') {
                $template = [IO.File]::ReadAllText((Join-Path $PSScriptRoot '../Templates/Component.vcxproj.in'))
                $definitions = if ($variant -eq 'Dynamic') { '      <PreprocessorDefinitions>UNIVERSALDEVKIT_' + $component.name.ToUpperInvariant() + '_DYNAMIC;UNIVERSALDEVKIT_' + $component.name.ToUpperInvariant() + '_EXPORTS;%(PreprocessorDefinitions)</PreprocessorDefinitions>' } else { '' }
                $type = if ($variant -eq 'Dynamic') { 'DynamicLibrary' } else { 'StaticLibrary' }
                $content = $template.Replace('@COMPONENT@', $component.name).Replace('@GUID@', $guid.Trim('{}')).Replace('@CONFIGURATION_TYPE@', $type).Replace('@DYNAMIC_DEFINITIONS@', $definitions)
                $graph = Resolve-UdkLinkageGraph @($component.name) @{ $component.name = $variant } $registry
                $standard = 20
                foreach ($requiredName in $graph.RequirementComponents) { $standard = [Math]::Max($standard, [int]$byName[$requiredName].requirements.cxxStandard) }
                if ($standard -eq 23) { $content = $content.Replace('stdcpp20', 'stdcpplatest') }
                AddOutput $path $content
            } else {
                $lines = @('<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by ProjectTools. Edit component descriptions and build extensions. -->', '<Project DefaultTargets="Build" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">', '  <ItemGroup Label="ProjectConfigurations">')
                foreach ($configuration in $Model.Settings.configurations) { foreach ($platform in $Model.Settings.platforms) { $lines += '    <ProjectConfiguration Include="' + $configuration + '|' + $platform + '"><Configuration>' + $configuration + '</Configuration><Platform>' + $platform + '</Platform></ProjectConfiguration>' } }
                $lines += @('  </ItemGroup>', '  <PropertyGroup Label="Globals">', ('    <ProjectGuid>' + $guid + '</ProjectGuid>'), '    <Keyword>Win32Proj</Keyword><WindowsTargetPlatformVersion>10.0</WindowsTargetPlatformVersion>')
                foreach ($property in $component.msbuild.properties.PSObject.Properties) {
                    if ($property.Name -notmatch '^[A-Za-z_][A-Za-z0-9_]*$' -or $property.Name -eq 'ProjectGuid') { throw 'Invalid MSBuild property.' }
                    $lines += '    <' + $property.Name + '>' + (ConvertTo-ProjectToolsXml $property.Value) + '</' + $property.Name + '>'
                }
                $type = if ($variant -eq 'Static') { 'StaticLibrary' } else { 'DynamicLibrary' }
                $lines += @('  </PropertyGroup>', '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.Default.props" />', ('  <PropertyGroup Label="Configuration"><ConfigurationType>' + $type + '</ConfigurationType><PlatformToolset>$(DefaultPlatformToolset)</PlatformToolset><UseDebugLibraries Condition="''$(Configuration)'' == ''Debug''">true</UseDebugLibraries><CharacterSet>Unicode</CharacterSet></PropertyGroup>'), '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.props" />')
                foreach ($props in $Model.Settings.props) { $lines += '  <Import Project="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $props)) + '" />' }
                $lines += '  <ImportGroup Label="Shared"><Import Project="' + [IO.Path]::GetFileName($sharedPath) + '" Label="Shared" /></ImportGroup>'
                if ($variant -eq 'Dynamic' -and $component.msbuild.dynamicDefinitions) { $lines += '  <ItemDefinitionGroup><ClCompile><PreprocessorDefinitions>' + (ConvertTo-ProjectToolsXml ($component.msbuild.dynamicDefinitions -join ';')) + ';%(PreprocessorDefinitions)</PreprocessorDefinitions></ClCompile></ItemDefinitionGroup>' }
                $graph = Resolve-UdkLinkageGraph @($component.name) @{ $component.name = $variant } $registry
                foreach ($dependencyName in $graph.ResolvedComponents) {
                    if ($dependencyName -eq $component.name -or $registry[$dependencyName].Kind -eq 'headerOnly') { continue }
                    $dependencyPath = Get-ProjectToolsLocation $Model $byName[$dependencyName] $graph.ResolvedModes[$dependencyName]
                    $lines += '  <ItemGroup><ProjectReference Include="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $dependencyPath)) + '" /></ItemGroup>'
                }
                $lines += '  <Import Project="$(VCTargetsPath)\Microsoft.Cpp.targets" />'
                if ($component.buildExtensions.msbuildTargets) { $lines += '  <Import Project="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $component.buildExtensions.msbuildTargets)) + '" />' }
                foreach ($targets in $Model.Settings.targets) { $lines += '  <Import Project="' + (ConvertTo-ProjectToolsXml (Get-ProjectToolsRelativeImport $Model $path $targets)) + '" />' }
                $lines += '</Project>'
                AddOutput $path ($lines -join "`n")
                AddOutput ($path + '.filters') ($filterLines -join "`n")
            }
        }
        if ($Model.Profile -eq 'udk' -and $component.kind -eq 'headerOnly') {
            $path = Get-ProjectToolsLocation $Model $component 'HeaderCheck'
            $guid = Get-ProjectToolsGuid (([Guid]$component.msbuildGuid).ToString('D') + ':HeaderCheck')
            $projects.Add([pscustomobject]@{ Path = $path; Guid = $guid; Variant = 'HeaderCheck'; Component = $component.name })
        }
    }
    foreach ($component in $Model.Applications.Values) {
        $guid = ([Guid]$component.msbuildGuid).ToString('B').ToUpperInvariant()
        if ($component.projectType -ceq 'wpf') {
            $directory = if ($Model.Profile -eq 'udk') { 'Projects/DotNet/' + $component.name }
                else { $Model.Settings.projectDirectory.Replace('{name}', $component.name) }
            $path = "$directory/$($component.name).csproj"
            $projects.Add([pscustomobject]@{ Path = $path; Guid = $guid; Variant = 'DotNet'; Component = $component.name })
            AddOutput $path (New-ProjectToolsWpfApplicationProject $Model $component $path)
            continue
        }
        $path = $Model.Settings.projectDirectory.Replace('{name}', $component.name) + '/' + $component.name + '.vcxproj'
        $projects.Add([pscustomobject]@{ Path = $path; Guid = $guid; Variant = 'Application'; Component = $component.name })
        $sharedPath = Get-ProjectToolsLocation $Model $component 'Shared'
        $sharedGuid = Get-ProjectToolsGuid (([Guid]$guid).ToString('D') + ':Shared')
        $projects.Add([pscustomobject]@{ Path = $sharedPath; Guid = $sharedGuid; Variant = 'Shared'; Component = $component.name })
        AddOutput $sharedPath (New-ProjectToolsApplicationSharedProject $Model $component $sharedPath $sharedGuid)
        AddOutput $path (New-ProjectToolsApplicationProject $Model $component $path $sharedPath)
    }
    if (@($projects.Guid | Sort-Object -Unique).Count -ne $projects.Count) { throw 'Duplicate project GUID.' }
    return [pscustomobject]@{ Files = $plan; Projects = $projects }
}